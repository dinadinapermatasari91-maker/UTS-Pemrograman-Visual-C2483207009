    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
try {
    if (txtTotal.getText().trim().isEmpty()
            || txtBayar.getText().trim().isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Silakan hitung total dan masukkan uang pembayaran!");
        return;
    }

    int total = Integer.parseInt(txtTotal.getText());
    int bayar = Integer.parseInt(txtBayar.getText());

    if (bayar < 0) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Uang pembayaran tidak boleh negatif!");
        return;
    }

    if (bayar < total) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Pembayaran kurang Rp" + (total - bayar));
        txtKembalian.setText("");
        return;
    }

    int kembalian = bayar - total;

    txtKembalian.setText(String.valueOf(kembalian));

    javax.swing.JOptionPane.showMessageDialog(this,
            "Pembayaran berhasil!\nUang Kembalian: Rp" + kembalian);

} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Pembayaran harus berupa angka!");
}        // TODO add your handling code here:
    }//GEN-LAST:event_jButton2ActionPerformed

